"""
Расширения Flask для приложения.

Студенты: этот файл демонстрирует важный паттерн инициализации Flask-расширений.

Почему мы создаём db = SQLAlchemy() БЕЗ передачи app?

1. Разделение ответственности: расширения создаются в одном файле, а привязываются
   к приложению в create_app() через init_app(). Это позволяет импортировать
   db из других модулей (models, repositories) без создания Flask-приложения.

2. Тестируемость: можно создать тестовое приложение с отдельной БД,
   не переопределяя объект db.

3. Несколько приложений: один объект db может использоваться несколькими
   Flask-приложениями в одном процессе (например, для изолированных тестов).

Альтернатива: SQLAlchemy(app) привязывает расширение к конкретному приложению
на этапе создания, что усложняет тестирование и повторное использование кода.

Паттерн:
  1. Создаём пустые экземпляры расширений здесь (без app)
  2. Импортируем их в app/__init__.py
  3. Вызываем init_app(app) для привязки к конкретному приложению
"""
from flask_sqlalchemy import SQLAlchemy
from flask_migrate import Migrate
from flask_login import LoginManager
from flask_wtf.csrf import CSRFProtect

# Расширения инициализируются БЕЗ app — привязка произойдёт в create_app() через init_app()
db = SQLAlchemy()
migrate = Migrate()
login_manager = LoginManager()
csrf = CSRFProtect()